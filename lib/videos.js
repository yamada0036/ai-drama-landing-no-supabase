export function watchBySlug(slug) {
  return watchVideos.find((video) => video.slug === slug);
}

export function videoObject(video) {
  return {
    '@context': 'https://schema.org',
    '@type': 'VideoObject',
    name: video.schemaName,
    description: video.schemaDescription,
    thumbnailUrl: [absoluteUrl(video.poster)],
    uploadDate: video.uploadDate,
    duration: video.durationIso,
    contentUrl: absoluteUrl(video.src),
    encodingFormat: 'video/mp4',
    width: video.width,
    height: video.height,
    isFamilyFriendly: true,
    inLanguage: 'en',
    publisher: {
      '@type': 'Organization',
      name: 'Moon Ocean Studio',
      url: SITE
    }
  };
}

export function videoSitemapEntry(video) {
  return {
    title: video.schemaName,
    thumbnail_loc: absoluteUrl(video.poster),
    description: video.schemaDescription,
    content_loc: absoluteUrl(video.src),
    duration: video.durationSeconds,
    publication_date: video.uploadDate,
    family_friendly: 'yes'
  };
}
